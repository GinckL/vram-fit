"""Regenerate llms-full.txt: the complete vram-fit documentation flattened into one Markdown file.

Sources: README.md, AGENT_GUIDE.md, the live argparse help of every sub-command, the quantization
registry, the GPU preset database, the offline catalog, the server protocol docstring and schema.json.

    python scripts/build_llms_full.py
"""

from __future__ import annotations

import io
import json
import os
import sys
from contextlib import redirect_stdout

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, os.path.join(ROOT, "src"))
os.environ["COLUMNS"] = "110"

from vram_fit import __version__  # noqa: E402
from vram_fit.catalog import ALIASES, CATALOG  # noqa: E402
from vram_fit.cli import build_parser  # noqa: E402
from vram_fit.estimator import ENGINES, MODES, OPTIMIZERS  # noqa: E402
from vram_fit.presets import PRESETS  # noqa: E402
from vram_fit.quant import QUANTS  # noqa: E402


def read(name: str) -> str:
    with open(os.path.join(ROOT, name), "r", encoding="utf-8") as f:
        return f.read()


def cli_help() -> str:
    parser = build_parser()
    out = ["## CLI reference (generated from `--help`)", ""]
    buf = io.StringIO()
    with redirect_stdout(buf):
        parser.print_help()
    out += ["### vram-fit", "", "```text", buf.getvalue().rstrip(), "```", ""]
    sub = next(a for a in parser._actions if a.__class__.__name__ == "_SubParsersAction")
    seen = set()
    for name, p in sub.choices.items():
        if id(p) in seen:
            continue
        seen.add(id(p))
        buf = io.StringIO()
        with redirect_stdout(buf):
            p.print_help()
        out += [f"### vram-fit {name}", "", "```text", buf.getvalue().rstrip(), "```", ""]
    return "\n".join(out)


def quant_table() -> str:
    rows = ["## Quantization formats", "", "| name | family | bits/weight | engines | description |", "|---|---|---|---|---|"]
    for q in QUANTS.values():
        rows.append(f"| {q.name} | {q.family} | {q.nominal_bpw:.2f} | {', '.join(q.engines)} | {q.description} |")
    rows += ["", "EXL2 accepts any bits/weight from 2.0 to 8.0 (`EXL2-4.65`, `5.0bpw`).", ""]
    return "\n".join(rows)


def preset_table() -> str:
    rows = ["## GPU presets (`--gpu <id>`, multi-GPU: `--gpu \"2x <id>\"`)", "",
            "| id | name | vendor | VRAM GiB | usable GiB | GB/s | FP16 TFLOPS | arch |", "|---|---|---|---|---|---|---|---|"]
    for g in PRESETS:
        rows.append(f"| {g.id} | {g.name} | {g.vendor} | {g.vram_gib:g} | {g.usable_gib:g} | {g.bandwidth_gbs:g} | "
                    f"{g.tflops:g} | {g.arch} |")
    return "\n".join(rows) + "\n"


def catalog_table() -> str:
    inv = {v: k for k, v in ALIASES.items()}
    rows = ["## Offline model catalog (works with `--offline`; also used when the Hub is unreachable)", "",
            "| id | alias | model_type | layers | hidden | heads/kv |", "|---|---|---|---|---|---|"]
    for cid, cfg in CATALOG.items():
        c = cfg.get("text_config") or cfg
        rows.append(f"| {cid} | {inv.get(cid, '')} | {cfg.get('model_type')} | {c.get('num_hidden_layers')} | "
                    f"{c.get('hidden_size')} | {c.get('num_attention_heads')}/{c.get('num_key_value_heads')} |")
    return "\n".join(rows) + "\n"


def server_doc() -> str:
    import ast
    tree = ast.parse(read("src/vram_fit/server.py"))
    doc = ast.get_docstring(tree) or ""
    return "## HTTP + WebSocket protocol (`vram-fit serve`)\n\n```text\n" + doc + "\n```\n"


def enums() -> str:
    return ("## Enumerations\n\n"
            f"- engines: {', '.join(ENGINES)}\n"
            f"- modes: {', '.join(MODES)}\n"
            f"- optimizers: {', '.join(OPTIMIZERS)}\n"
            "- gradient checkpointing: none, standard, unsloth\n"
            "- KV cache: llama.cpp/Ollama f16 bf16 f32 q8_0 q5_1 q5_0 q4_1 q4_0 iq4_nl (or bits 16/8/4); "
            "vLLM auto fp8 fp8_e4m3 fp8_e5m2; ExLlamaV2 FP16 Q8 Q6 Q4\n"
            "- status: fits, tight, offload, spill, oom\n"
            "- segments: weights (Model Weights), kv_cache (KV Cache), activations (Activation Buffers), "
            "overhead (CUDA/Driver Overhead), lora_optimizer (LoRA/Optimizer States)\n")


def main() -> None:
    parts = [
        f"# vram-fit {__version__} — complete documentation (flattened for LLM ingestion)",
        "",
        "> Source: https://github.com/GinckL/vram-fit — regenerated by scripts/build_llms_full.py. "
        "This single file contains the README, the agent guide, the full CLI reference, all quantization formats, "
        "all GPU presets, the offline model catalog, the HTTP/WebSocket protocol and the JSON output schema.",
        "",
        "---",
        "",
        read("README.md").strip(),
        "",
        "---",
        "",
        read("AGENT_GUIDE.md").strip(),
        "",
        "---",
        "",
        cli_help(),
        enums(),
        quant_table(),
        preset_table(),
        catalog_table(),
        server_doc(),
        "## JSON output schema (schema.json)\n\n```json\n" + json.dumps(json.loads(read("schema.json")), indent=1) + "\n```\n",
    ]
    with open(os.path.join(ROOT, "llms-full.txt"), "w", encoding="utf-8") as f:
        f.write("\n".join(parts))
    print(f"wrote llms-full.txt ({sum(len(p) for p in parts):,} chars)")


if __name__ == "__main__":
    main()
